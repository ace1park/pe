function glossGuideHTML(){
  const used=new Set(UORDER);
  return GLOSS_GROUPS.filter(([k])=>k==='*'||k.split(',').some(u=>used.has(u))).map(([k,t],gi)=>{
    const L=GLOSS.filter(g=>g[1]===k||(k!=='*'&&g[1]!=='*'&&g[1].split(',')[0]===k.split(',')[0]));
    return L.length?`<details class="glgrp" ${gi===0?'open':''}><summary>${t} <small>${L.length}개</small></summary>${glossList(L)}</details>`:'';
  }).join('');
}
