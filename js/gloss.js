const GLOSS_EASY=['교대'];
/* 종목 낱말을 먼저, 공통 낱말은 뒤에 */
const GLOSSRE=GLOSS.map(([w,,,re])=>new RegExp(re||w.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')));
function glossOk(g,unit){ return g[1]==='*'||g[1].split(',').includes(unit); }
/* 글 묶음에서 그 단원에 맞는 낱말 찾기(나온 순서대로, 최대 n개) */
function glossFind(texts,unit,n=8){
  const s=texts.filter(Boolean).join('\n'), hit=[];
  GLOSS.forEach((g,k)=>{ if(glossOk(g,unit)&&!(n<99&&GLOSS_EASY.includes(g[0]))){ const m=GLOSSRE[k].exec(s); if(m) hit.push([(g[1]==='*'?1e6:0)+m.index,g]); } });
  return hit.sort((a,b)=>a[0]-b[0]).slice(0,n).map(x=>x[1]);
}
