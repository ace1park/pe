(function(){
  const clone=o=>Array.isArray(o)?o.map(clone):(o&&typeof o==='object')?Object.fromEntries(Object.entries(o).map(([k,v])=>[k,clone(v)])):o;
  const sub=(s,pairs)=>typeof s!=='string'?s:pairs.reduce((a,[x,y])=>a.split(x).join(y),s);
  const deep=(o,pairs)=>Array.isArray(o)?o.map(v=>deep(v,pairs)):(o&&typeof o==='object')?Object.fromEntries(Object.entries(o).map(([k,v])=>[k,deep(v,pairs)])):sub(o,pairs);
  for(let n=1;n<=20;n++){
    const src=DETAIL[n]; if(!src) continue;
    const d=clone(src);
    d.m=d.m.map((m,i)=>{
      const key=n+'-'+(i+1);
      if(FOOT3.활동바꾸기[key]) return clone(FOOT3.활동바꾸기[key]);
      const easyT=m.t&&m.t.easy, easyS=m.easy;
      m=deep(m,FOOT3.바꿀말.concat(FOOT3.골문기본));
      if(m.t&&easyT) m.t.easy=sub(deep(easyT,FOOT3.바꿀말),FOOT3.골문쉽게);
      if(easyS) m.easy=sub(deep(easyS,FOOT3.바꿀말),FOOT3.골문쉽게);
      if(m.d&&m.d.gk) delete m.d.gk;
      if(m.d&&m.d.t==='shape') m.d.three=true;
      const fix=FOOT3.칸바꾸기[key];
      if(fix) Object.entries(fix).forEach(([k,v])=>{ if(['prep','odd','how','point'].includes(k)){ m.t=m.t||{}; m.t[k]=v; } else m[k]=v; });
      if(m.t && m.t.point && !m.t.point.includes('걸어서만') && /수비|\d:\d|술래|상어/.test(JSON.stringify(m)) && !/^(개인|2인)$/.test(m.form||'')) m.t.point+=FOOT3.수비;
      return m;
    });
    DETAIL[n+100]=d;
  }
})();
